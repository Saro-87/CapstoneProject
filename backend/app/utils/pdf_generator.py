from io import BytesIO
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.colors import darkblue
from reportlab.lib.units import inch
from reportlab.lib.styles import ParagraphStyle
from datetime import datetime


def generate_pdf(report_data):
    buffer = BytesIO()

    doc = SimpleDocTemplate(buffer)

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "Title",
        parent=styles["Heading1"],
        alignment=TA_CENTER,
        textColor=darkblue,
        spaceAfter=20,
    )

    story = []

    story.append(Paragraph("AWS FinOps Report", title_style))
    story.append(
        Paragraph(
            f"Generated on: {datetime.now().strftime('%d-%b-%Y %H:%M')}",
            styles["Normal"],
        )
    )

    story.append(Spacer(1, 0.3 * inch))

    story.append(
        Paragraph(
            f"<b>Monthly Cost:</b> ${report_data['monthly_cost']}",
            styles["Normal"],
        )
    )

    story.append(
        Paragraph(
            f"<b>Budget:</b> ${report_data['budget']}",
            styles["Normal"],
        )
    )

    story.append(
        Paragraph(
            f"<b>Spent:</b> ${report_data['spent']}",
            styles["Normal"],
        )
    )

    story.append(
        Paragraph(
            f"<b>Remaining:</b> ${report_data['remaining']}",
            styles["Normal"],
        )
    )

    story.append(
        Paragraph(
            f"<b>Total Resources:</b> {report_data['resources']}",
            styles["Normal"],
        )
    )

    story.append(
        Paragraph(
            f"<b>Estimated Savings:</b> ${report_data['estimated_savings']}",
            styles["Normal"],
        )
    )

    story.append(Spacer(1, 0.5 * inch))

    story.append(
        Paragraph(
            "Generated by Multi-Cloud FinOps Dashboard",
            styles["Italic"],
        )
    )

    doc.build(story)

    buffer.seek(0)

    return buffer